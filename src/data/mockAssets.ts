import type { Asset, AssetDocument, AssetTimelineEvent } from '@/types';
import { getAssetUrl } from '@/utils/assets';

/* Map an asset category to a product photo (served from /public/assets). */
const CATEGORY_IMAGE: Record<string, string> = {
  'Pump': getAssetUrl('assets/Pump.webp'),
  'Mixer': getAssetUrl('assets/Mixer.webp'),
  'Service': getAssetUrl('assets/Service.webp'),
  'Spare Part': getAssetUrl('assets/Sparepart.webp'),
  'Other': getAssetUrl('assets/Other.webp'),
};

function withImage(a: Asset): Asset {
  if (a.image || !CATEGORY_IMAGE[a.category]) return a;
  return { ...a, image: CATEGORY_IMAGE[a.category] };
}

function docs(name: string, extra: AssetDocument[] = []): AssetDocument[] {
  return [
    { name: `${name} — Datasheet.pdf`, type: 'datasheet', date: '2023-11-02', size: '1.2 MB' },
    { name: `${name} — Warranty certificate.pdf`, type: 'warranty', date: '2024-01-18', size: '340 KB' },
    { name: `${name} — Installation report.pdf`, type: 'installation', date: '2024-01-15', size: '2.4 MB' },
    { name: `${name} — Commissioning report.pdf`, type: 'commissioning', date: '2024-01-18', size: '1.8 MB' },
    { name: `${name} — Product manual.pdf`, type: 'manual', date: '2023-11-02', size: '5.6 MB' },
    ...extra,
  ];
}

function lifecycle(sale: string, install: string, commission: string, extra: AssetTimelineEvent[] = []): AssetTimelineEvent[] {
  const base: AssetTimelineEvent[] = [
    { date: sale, type: 'sale', title: 'Purchase order confirmed', detail: 'Equipment supplied by SiamEast Solutions PCL.' },
    { date: install, type: 'installation', title: 'Installed on site', detail: 'Installation completed by SE field service team.' },
    { date: commission, type: 'commissioning', title: 'Commissioned and handed over', detail: 'Performance test passed. Warranty period started.' },
    ...extra,
  ];
  return base.sort((a, b) => (a.date < b.date ? 1 : -1));
}

